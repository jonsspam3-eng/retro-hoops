let idSeed = 1;

function nextId() {
  const id = idSeed;
  idSeed += 1;
  return id;
}

function createPlayer(name, position, classYear, archetype, ratings, heightInches) {
  return {
    id: `p-${nextId()}`,
    name,
    position,
    classYear,
    archetype,
    heightInches,
    ratings,
    stamina: 100,
    hotStreak: 0,
  };
}

export function cloneRoster(roster) {
  return roster.map((player) => ({
    ...player,
    ratings: { ...player.ratings },
    stamina: 100,
    hotStreak: 0,
  }));
}

